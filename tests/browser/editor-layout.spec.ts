test("content shortcut searches text and Escape returns focus to status action", async ({ page }) => {
  await page.goto("/")
  const trigger = page.getByRole("button", { name: /^Find in files/ })
  await trigger.focus()
  await trigger.press("ControlOrMeta+Shift+f")
  const search = page.getByRole("combobox", { name: "Search document content…" })
  await expect(search).toBeFocused()
  await search.fill("luminous-orchid")
  await expect(page.getByRole("option").filter({ hasText: "search.md" })).toBeVisible()
  await search.press("Escape")
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(search).toHaveValue("luminous-orchid")
})

test("mobile explorer opens, selects, and closes without reserving reading space", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/view?path=guides%2Fgetting-started.md")
  await page.getByRole("button", { name: "Preview", exact: true }).click()
  await expect(page.locator(".explorer-drawer")).toBeHidden()
  await expect(page.locator("article")).toHaveCSS("font-size", "16px")
  await page.getByRole("button", { name: "Open files" }).click()
  const drawer = page.getByRole("dialog", { name: "Files", exact: true })
  await expect(drawer).toBeVisible()
  const search = drawer.getByRole("textbox", { name: "Search…" })
  const searchToggle = drawer.getByRole("button", { name: "Search files" })
  await expect(search).toBeHidden()
  await searchToggle.click()
  await expect(search).toBeFocused()
  await searchToggle.click()
  await expect(search).toBeHidden()
  await expect(drawer).toBeVisible()
  await searchToggle.click()
  await expect(search).toBeFocused()
  await search.press("Escape")
  await expect(search).toBeHidden()
  await drawer.getByRole("treeitem", { name: "code-blocks.md" }).click()
  await expect(drawer).toBeHidden()
  await expect(page).toHaveURL(/path=guides%2Fcode-blocks.md/)
  await page.getByRole("button", { name: "Open files" }).click()
  await drawer.getByRole("treeitem", { name: "code-blocks.md" }).click()
  await expect(drawer).toBeHidden()
  await expect(page.getByRole("button", { name: /^Find in files/ })).toBeVisible()
  await expect(page.locator(".status-path")).toBeVisible()
  await expect(page.locator(".status-path")).toHaveText("guides/code-blocks.md")
  await expect(page.getByRole("button", { name: "Theme: System" })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

