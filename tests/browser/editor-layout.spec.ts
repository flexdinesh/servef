import { expect, test } from "@playwright/test"

test("file tree supports arrow navigation and Enter activation", async ({ page }) => {
  await page.goto("/")
  const explorer = page.getByRole("complementary", { name: "Files" })
  const directory = explorer.getByRole("treeitem", { name: "guides", exact: true })
  await directory.focus()
  await directory.press("ArrowRight")
  await directory.press("ArrowDown")
  await explorer.getByRole("treeitem", { name: "code-blocks.md" }).press("Enter")
  await expect(page).toHaveURL(/path=guides%2Fcode-blocks.md/)
})

test("mobile explorer opens, selects, and closes without reserving reading space", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/view?path=guides%2Fgetting-started.md")
  await page.getByRole("button", { name: "Preview", exact: true }).click()
  await expect(page.locator(".explorer-drawer")).toBeHidden()
  await expect(page.locator("article")).toHaveCSS("font-size", "15px")
  await page.getByRole("button", { name: "Open files" }).click()
  const drawer = page.getByRole("dialog", { name: "Files", exact: true })
  await expect(drawer).toBeVisible()
  const search = drawer.getByRole("textbox", { name: "Search…" })
  const searchToggle = drawer.getByRole("button", { name: "Search files" })
  await expect(search).toBeHidden()
  await searchToggle.click()
  await expect(search).toBeFocused()
  await searchToggle.click()
  await expect(search).toBeHidden()
  await expect(drawer).toBeVisible()
  await searchToggle.click()
  await expect(search).toBeFocused()
  await search.press("Escape")
  await expect(search).toBeHidden()
  await drawer.getByRole("treeitem", { name: "code-blocks.md" }).click()
  await expect(drawer).toBeHidden()
  await expect(page).toHaveURL(/path=guides%2Fcode-blocks.md/)
  await page.getByRole("button", { name: "Open files" }).click()
  await drawer.getByRole("treeitem", { name: "code-blocks.md" }).click()
  await expect(drawer).toBeHidden()
  await expect(page.locator(".status-bar").getByRole("button", { name: /^Find in files/ })).toBeVisible()
  await expect(page.locator(".status-path")).toBeVisible()
  await expect(page.locator(".status-path")).toHaveText("guides/code-blocks.md")
  await expect(page.getByRole("button", { name: "Settings", exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test("mobile content search opens in the drawer and closes it when a match opens", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/")
  await page.locator(".status-bar").getByRole("button", { name: /^Find in files/ }).click()
  const drawer = page.getByRole("dialog", { name: "Search", exact: true })
  const search = drawer.getByRole("textbox", { name: "Search", exact: true })
  await expect(search).toBeFocused()
  await search.fill("luminous-orchid")
  await drawer.getByRole("treeitem").filter({ hasText: "phrase **luminous-orchid**" }).click()
  await expect(drawer).toBeHidden()
  await expect(page).toHaveURL(/path=reference%2Ftopics%2Fsearch.md#L3$/)
  await page.getByRole("button", { name: "Open files" }).click()
  await expect(page.getByRole("dialog", { name: "Files", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Search", exact: true }).click()
  await expect(drawer).toBeVisible()
  await expect(search).toHaveValue("luminous-orchid")
  await drawer.getByRole("button", { name: "Close search" }).click()
  await expect(drawer).toBeHidden()
})
