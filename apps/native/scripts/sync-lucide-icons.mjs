// sync-lucide-icons.mjs ports the Lucide icons the workspace shell draws
// (the web's lucide-react icons, at the version the web locks) into
// apps/native/internal/view/lucide_icons.go, and copies Lucide's LICENSE
// (ISC, with Feather's MIT) beside it. Run it after a version bump or an
// added icon, then gofmt the output:
//
//   node apps/native/scripts/sync-lucide-icons.mjs apps/web
import { copyFileSync, readFileSync, realpathSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

// icons maps the Go names to Lucide's.
const icons = {
  Files: "files", Search: "search", GitBranch: "git-branch", Route: "route",
  X: "x", GitCompareArrows: "git-compare-arrows",
}

const web = process.argv[2]
if (!web) {
  console.error("usage: sync-lucide-icons.mjs <web package dir>")
  process.exit(1)
}
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "internal", "view")
const dir = realpathSync(join(web, "node_modules", "lucide-react"))
const version = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).version

const attrs = (props) => Object.entries(props).filter(([key]) => key !== "key").map(([key, value]) => `${key}="${value}"`).join(" ")
let body = ""
for (const [name, file] of Object.entries(icons)) {
  const { __iconData: data } = await import(pathToFileURL(join(dir, "dist", "esm", "icons", `${file}.mjs`)).href)
  const shapes = data.node.map(([tag, props]) => `<${tag} ${attrs(props)}/>`).join("")
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${shapes}</svg>`
  body += `\t// lucide${name} is Lucide's ${file}.\n\tlucide${name} = ui.MustParseSVG([]byte(\`${svg}\`))\n`
}
writeFileSync(join(out, "lucide_icons.go"), `// Code generated by apps/native/scripts/sync-lucide-icons.mjs; DO NOT EDIT.

package view

import "github.com/egoist/mygo/ui"

// LucideVersion is the lucide-react release the icons come from, the web's.
const LucideVersion = "${version}"

var (
${body})
`)
copyFileSync(join(dir, "LICENSE"), join(out, "LUCIDE-LICENSE"))
