// goldens.mjs regenerates what packages/mygo checks its WebAssembly ports
// against, from the JavaScript glue the web app runs (sync-wasm.sh runs it):
//
//   - highlights/languages.go and scopes.go: Highlights' language IDs and
//     token scope names.
//   - highlights/testdata/tokens.json: codeToTokens' lines for every sample
//     in highlights/testdata/samples (<name>.<language>), as [content,
//     scope] pairs, plus "@1000" entries with tokenizeMaxLineLength 1000.
//   - ondine/testdata/renders.json: Render.create(...).render for every
//     ondine/testdata/*.mmd at the options the tests use.
//
//   node packages/mygo/scripts/goldens.mjs <web package dir>
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const web = resolve(process.argv[2] ?? "")
const here = join(dirname(fileURLToPath(import.meta.url)), "..")
const require = createRequire(join(web, "package.json"))

// Highlights.
const highlightsDir = dirname(require.resolve("@pierre/highlights/package.json"))
const highlights = await import(pathToFileURL(join(highlightsDir, "dist", "default.js")).href)
const { default: languages } = await import(pathToFileURL(join(highlightsDir, "dist", "languages.js")).href)
const scopes = highlights.tokenNames

const goStrings = (values) => values.map((value) => `\t${JSON.stringify(value)},`).join("\n")
writeFileSync(join(here, "highlights", "languages.go"), `// Code generated by packages/mygo/scripts/goldens.mjs; DO NOT EDIT.

package highlights

// languageIDs maps every name and alias Highlights knows (lowercase) to its
// lexer's ID (dist/languages.js).
var languageIDs = map[string]uint8{
${Object.entries(languages).map(([name, id]) => `\t${JSON.stringify(name)}: ${id},`).join("\n")}
}
`)
writeFileSync(join(here, "highlights", "scopes.go"), `// Code generated by packages/mygo/scripts/goldens.mjs; DO NOT EDIT.

package highlights

// scopeNames are Highlights' token scopes by ID (dist/token-types.js).
var scopeNames = [...]string{
${goStrings(scopes)}
}
`)

// A probe theme gives every scope its own color, so a token's color names
// its scope; the foreground (scope 0, "none") is #fffffe.
const hex = (i) => `#0000${i.toString(16).padStart(2, "0")}`
const probe = {
  name: "probe",
  style: { "editor.foreground": "#fffffe", syntax: Object.fromEntries(scopes.map((name, i) => [name, hex(i)]).slice(1)) },
}
const scopeOf = new Map(scopes.map((name, i) => [hex(i), name]))
scopeOf.set("#fffffe", scopes[0])

const tokens = {}
const samples = join(here, "highlights", "testdata", "samples")
for (const file of readdirSync(samples).sort()) {
  const lang = file.slice(file.lastIndexOf(".") + 1)
  const source = readFileSync(join(samples, file), "utf8")
  for (const max of [0, 1000]) {
    if (max > 0 && !file.startsWith("long.")) continue
    const { tokens: lines } = highlights.codeToTokens(source, { lang, theme: probe, tokenizeMaxLineLength: max || undefined })
    tokens[max ? `${file}@${max}` : file] = lines.map((line) => line.map((token) => {
      const scope = scopeOf.get(token.color)
      if (scope === undefined) throw new Error(`${file}: unknown color ${token.color}`)
      return [token.content, scope]
    }))
  }
}
// One line of tokens per row keeps diffs readable.
const rows = Object.entries(tokens).map(([file, lines]) => `${JSON.stringify(file)}: [\n${lines.map((line) => `  ${JSON.stringify(line)}`).join(",\n")}\n ]`)
writeFileSync(join(here, "highlights", "testdata", "tokens.json"), `{\n ${rows.join(",\n ")}\n}\n`)

// Ondine.
const ondineDir = dirname(require.resolve("ondine/compiler/wasm"))
const { create } = await import(pathToFileURL(require.resolve("ondine/compiler/wasm")).href)
const all = new WebAssembly.Module(readFileSync(join(ondineDir, "..", "internal", "all.generated.wasm")))
const renderer = create({ modules: { all } })
const renders = {}
const diagrams = join(here, "ondine", "testdata")
// The options the tests pass; now is fixed so gantt charts are stable.
const options = { idPrefix: "golden", maxWidth: 720, padding: 16, now: Date.UTC(2026, 0, 15) }
for (const file of readdirSync(diagrams).filter((name) => name.endsWith(".mmd")).sort()) {
  const source = readFileSync(join(diagrams, file), "utf8")
  try {
    const { svg, width, height, type, links } = renderer.render(source, options)
    renders[file] = { ok: true, type, width, height, links, svg }
  } catch (error) {
    const { code, line, column, snippet, message, type } = error
    renders[file] = { ok: false, code, type: type ?? "", line, column, snippet, message }
  }
}
writeFileSync(join(diagrams, "renders.json"), `${JSON.stringify({ options, renders }, null, 1)}\n`)
