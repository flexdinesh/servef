// sync-trees-icons.mjs ports @pierre/trees' built-in icon set (the
// "complete" sprite sheet, its file name and extension tables, and its
// colors) into packages/mygo/trees/pierre_icons.go, and copies Pierre's
// LICENSE.md and NOTICE.md beside it (Apache-2.0). Run it after a version
// bump, then gofmt the output:
//
//   node packages/mygo/scripts/sync-trees-icons.mjs <web package dir>
import { readFileSync, realpathSync, writeFileSync, copyFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const web = process.argv[2]
if (!web) {
  console.error("usage: sync-trees-icons.mjs <web package dir>")
  process.exit(1)
}
const here = join(dirname(fileURLToPath(import.meta.url)), "..", "trees")
const dir = realpathSync(join(web, "node_modules", "@pierre", "trees"))
const version = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).version
const source = readFileSync(join(dir, "dist", "builtInIcons.js"), "utf8")
const { getBuiltInSpriteSheet } = await import(pathToFileURL(join(dir, "dist", "builtInIcons.js")).href)
const { default: style } = await import(pathToFileURL(join(dir, "dist", "style.js")).href)

// table evaluates one object literal of builtInIcons.js: plain string data.
function table(name) {
  const match = source.match(new RegExp(`const ${name} = (\\{[\\s\\S]*?\\n\\});`))
  if (!match) throw new Error(`${name} not found`)
  return Function(`return ${match[1]}`)()
}

const symbols = {}
for (const match of getBuiltInSpriteSheet("complete").matchAll(/<symbol id="([^"]+)" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g)) {
  const [, id, viewBox, body] = match
  const name = id.replace(/^file-tree-builtin-/, "").replace(/^file-tree-icon-/, "icon-")
  symbols[name] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${body.trim().replace(/\n\s*/g, "")}</svg>`
}

const palette = {}
for (const match of style.matchAll(/--trees-icon-([a-z]+): light-dark\((#[0-9a-f]+), (#[0-9a-f]+)\);/g)) palette[match[1]] = [match[2], match[3]]
const colors = {}
for (const match of style.matchAll(/--trees-file-icon-color-([a-z]+): var\([^,]+, var\(--trees-icon-([a-z]+)\)\);/g)) colors[match[1]] = match[2]
const status = {}
for (const match of style.matchAll(/--trees-([a-z]+)-(light|dark): (#[0-9a-f]+);/g)) {
  status[match[1]] ??= ["", ""]
  status[match[1]][match[2] === "light" ? 0 : 1] = match[3]
}

const quote = (value) => JSON.stringify(value)
const raw = (value) => `\`${value}\``
const sorted = (object) => Object.keys(object).sort()
const strings = (object) => sorted(object).map((key) => `\t${quote(key)}: ${quote(object[key])},`).join("\n")
const pairs = (object) => sorted(object).map((key) => `\t${quote(key)}: {${quote(object[key][0])}, ${quote(object[key][1])}},`).join("\n")

writeFileSync(join(here, "pierre_icons.go"), `// Code generated by packages/mygo/scripts/sync-trees-icons.mjs from @pierre/trees@${version}; DO NOT EDIT.
// Pierre's icons and tables are Apache-2.0 (PIERRE-LICENSE.md, PIERRE-NOTICE.md).

package trees

// PierreVersion is the @pierre/trees release the icon set comes from.
const PierreVersion = ${quote(version)}

// pierreSymbols are the sprite sheet's symbols as SVG documents, by token
// ("icon-chevron", "icon-dot", and "icon-file" are the tree's own).
var pierreSymbols = map[string]string{
${sorted(symbols).map((key) => `\t${quote(key)}: ${raw(symbols[key])},`).join("\n")}
}

// pierreFileNames maps lower-case base names to tokens.
var pierreFileNames = map[string]string{
${strings(table("BUILT_IN_FILE_NAME_TOKENS"))}
}

// pierreExtensions maps lower-case extensions (without the dot, possibly
// compound) to tokens.
var pierreExtensions = map[string]string{
${strings(table("BUILT_IN_FILE_EXTENSION_TOKENS"))}
}

// pierreCompleteOverrides take precedence over pierreExtensions in the
// complete set.
var pierreCompleteOverrides = map[string]string{
${strings(table("COMPLETE_EXTENSION_OVERRIDES"))}
}

// pierreIconColors names each token's hue in pierrePalette.
var pierreIconColors = map[string]string{
${strings(colors)}
}

// pierrePalette is each hue's light and dark color.
var pierrePalette = map[string][2]string{
${pairs(palette)}
}

// pierreStatus is each git status's light and dark color.
var pierreStatus = map[string][2]string{
${pairs(status)}
}
`)
copyFileSync(join(dir, "LICENSE.md"), join(here, "PIERRE-LICENSE.md"))
copyFileSync(join(dir, "NOTICE.md"), join(here, "PIERRE-NOTICE.md"))
console.log(`synced @pierre/trees@${version}: ${Object.keys(symbols).length} symbols`)
