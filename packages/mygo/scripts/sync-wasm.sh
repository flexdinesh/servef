#!/bin/sh
# sync-wasm.sh copies the WebAssembly modules packages/mygo embeds
# (highlights, ondine) from a web package's installed dependencies, records
# each one's version, lockfile integrity, and sha256 in pin.go, and
# regenerates the token and SVG goldens with the same JavaScript glue the web
# app runs. Run it after a version bump:
#
#   sh packages/mygo/scripts/sync-wasm.sh <web package dir> <pnpm-lock.yaml>
set -eu

web=${1:?usage: sync-wasm.sh <web package dir> <pnpm-lock.yaml>}
lock=${2:?usage: sync-wasm.sh <web package dir> <pnpm-lock.yaml>}
here=$(cd "$(dirname "$0")/.." && pwd)

# integrity prints the lockfile's tarball integrity for name@version.
integrity() {
	awk -v key="  '$1@$2':" -v bare="  $1@$2:" '
		$0 == key || $0 == bare { found = 1; next }
		found && /integrity:/ { sub(/.*integrity: */, ""); sub(/}.*/, ""); print; exit }
		found && /^  [^ ]/ { exit }
	' "$lock"
}

# sync copies one module and writes its pin.go.
#   sync <package> <npm name> <wasm path in package> <dest name> <license files...>
sync() {
	pkg=$1 name=$2 wasm=$3 dest=$4
	shift 4
	dir=$(cd "$web/node_modules/$name" && pwd -P)
	version=$(node -p 'require(process.argv[1]).version' "$dir/package.json")
	sum=$(integrity "$name" "$version")
	if [ -z "$sum" ]; then
		echo "sync-wasm: $name@$version is not in $lock" >&2
		exit 1
	fi
	cp "$dir/$wasm" "$here/$pkg/$dest"
	for license in "$@"; do
		cp "$dir/$license" "$here/$pkg/$license"
	done
	sha=$(sha256sum "$here/$pkg/$dest" | cut -d' ' -f1)
	cat >"$here/$pkg/pin.go" <<GO
// Code generated by packages/mygo/scripts/sync-wasm.sh; DO NOT EDIT.

package $pkg

// The embedded module comes from $name@$version ($wasm).
const (
	// Version is the npm version the module was copied from.
	Version = "$version"
	// Integrity is that version's tarball integrity in the lockfile.
	Integrity = "$sum"
	// WasmSHA256 is the embedded module's sha256.
	WasmSHA256 = "$sha"
)
GO
	echo "$pkg: $name@$version $sha"
}

sync highlights @pierre/highlights dist/highlights.wasm highlights.wasm LICENSE.md NOTICE.md
sync ondine ondine dist/internal/all.generated.wasm all.wasm LICENSE
node "$here/scripts/goldens.mjs" "$web"
gofmt -w "$here/highlights/languages.go" "$here/highlights/scopes.go"
