package main

import (
	"fmt"
	"slices"
	"strings"
)

const header = "// Code generated by tools/contracts from apps/servef/pkg/contract%s. DO NOT EDIT.\n"

const guards = `
// isRecord reports a JSON object.
export function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
}

export function isString(value: unknown): value is string {
  return typeof value === "string"
}

export function isBoolean(value: unknown): value is boolean {
  return typeof value === "boolean"
}

export function isNumber(value: unknown): value is number {
  return typeof value === "number"
}

// isArrayOf reports an array whose every entry item accepts.
export function isArrayOf<T>(value: unknown, item: (entry: unknown) => entry is T): value is T[] {
  return Array.isArray(value) && value.every(item)
}
`

// emit renders the TypeScript package sources by file name.
func emit(m *model) map[string]string {
	output := map[string]string{"guards.ts": fmt.Sprintf(header, "") + guards}
	var index strings.Builder
	index.WriteString(fmt.Sprintf(header, ""))
	index.WriteString("\n")
	for _, source := range m.files {
		output[source.module+".ts"] = emitModule(m, source)
		fmt.Fprintf(&index, "export * from \"./%s.ts\"\n", source.module)
	}
	output["index.ts"] = index.String()
	return output
}

func emitModule(m *model, source *sourceFile) string {
	var body strings.Builder
	helpers := map[string]bool{}
	imports := map[string]map[string]bool{}
	use := func(name string) {
		decl := m.types[name]
		if decl.file == source {
			return
		}
		if imports[decl.file.module] == nil {
			imports[decl.file.module] = map[string]bool{}
		}
		imports[decl.file.module]["type "+name] = true
		imports[decl.file.module]["is"+name] = true
	}
	for _, decl := range source.decls {
		body.WriteString("\n")
		writeDoc(&body, "", decl.doc)
		if decl.kind == enumDecl {
			quoted := make([]string, len(decl.values))
			checks := make([]string, len(decl.values))
			for i, value := range decl.values {
				quoted[i] = quote(value)
				checks[i] = "value === " + quote(value)
			}
			fmt.Fprintf(&body, "export type %s = %s\n\n", decl.name, strings.Join(quoted, " | "))
			fmt.Fprintf(&body, "export function is%s(value: unknown): value is %s {\n  return %s\n}\n", decl.name, decl.name, strings.Join(checks, " || "))
			continue
		}
		fmt.Fprintf(&body, "export interface %s {\n", decl.name)
		for _, field := range decl.fields {
			writeDoc(&body, "  ", field.doc)
			optional := ""
			if field.optional {
				optional = "?"
			}
			fmt.Fprintf(&body, "  %s%s: %s\n", field.json, optional, tsType(field.ref, use))
		}
		body.WriteString("}\n\n")
		helpers["isRecord"] = true
		checks := []string{"isRecord(value)"}
		for _, field := range decl.fields {
			access := "value." + field.json
			check := guardCall(field.ref, access, helpers, use)
			if field.optional {
				check = fmt.Sprintf("(%s === undefined || %s)", access, check)
			}
			checks = append(checks, check)
		}
		for _, rule := range decl.rules {
			when := "!=="
			if !rule.when.equal {
				when = "==="
			}
			then := "==="
			if !rule.then.equal {
				then = "!=="
			}
			checks = append(checks, fmt.Sprintf("(%s %s %s || %s %s %s)", ruleAccess(decl, rule.when.field), when, rule.when.literal, ruleAccess(decl, rule.then.field), then, rule.then.literal))
		}
		fmt.Fprintf(&body, "export function is%s(value: unknown): value is %s {\n  return %s\n}\n", decl.name, decl.name, strings.Join(checks, "\n    && "))
	}

	var file strings.Builder
	fmt.Fprintf(&file, header, "/"+source.name)
	file.WriteString("\n")
	file.WriteString(importLine(sortedKeys(helpers), "./guards.ts"))
	modules := sortedKeys(imports)
	for _, module := range modules {
		names := sortedKeys(imports[module])
		slices.SortFunc(names, func(a, b string) int {
			return strings.Compare(strings.TrimPrefix(a, "type "), strings.TrimPrefix(b, "type "))
		})
		file.WriteString(importLine(names, "./"+module+".ts"))
	}
	file.WriteString(body.String())
	return file.String()
}

// ruleAccess reads a field for a rule; an absent optional string is "", as
// Go omits it.
func ruleAccess(decl *typeDecl, name string) string {
	if named, _ := decl.field(name); named.optional {
		return fmt.Sprintf("(value.%s ?? \"\")", name)
	}
	return "value." + name
}

func importLine(names []string, from string) string {
	if len(names) == 0 {
		return ""
	}
	return fmt.Sprintf("import { %s } from %q\n", strings.Join(names, ", "), from)
}

func tsType(ref typeRef, use func(string)) string {
	switch ref.kind {
	case stringRef:
		return "string"
	case booleanRef:
		return "boolean"
	case numberRef:
		return "number"
	case arrayRef:
		return tsType(*ref.elem, use) + "[]"
	case nullableRef:
		return tsType(*ref.elem, use) + " | null"
	}
	use(ref.name)
	return ref.name
}

// guardCall checks access against ref.
func guardCall(ref typeRef, access string, helpers map[string]bool, use func(string)) string {
	switch ref.kind {
	case nullableRef:
		return fmt.Sprintf("(%s === null || %s)", access, guardCall(*ref.elem, access, helpers, use))
	case arrayRef:
		helpers["isArrayOf"] = true
		return fmt.Sprintf("isArrayOf(%s, %s)", access, guardFunction(*ref.elem, helpers, use))
	}
	return guardFunction(ref, helpers, use) + "(" + access + ")"
}

// guardFunction is a guard for ref as a function value.
func guardFunction(ref typeRef, helpers map[string]bool, use func(string)) string {
	switch ref.kind {
	case stringRef:
		helpers["isString"] = true
		return "isString"
	case booleanRef:
		helpers["isBoolean"] = true
		return "isBoolean"
	case numberRef:
		helpers["isNumber"] = true
		return "isNumber"
	case namedRef:
		use(ref.name)
		return "is" + ref.name
	}
	return fmt.Sprintf("(entry: unknown): entry is %s => %s", tsType(ref, use), guardCall(ref, "entry", helpers, use))
}

func writeDoc(out *strings.Builder, indent string, lines []string) {
	for _, line := range lines {
		if line == "" {
			fmt.Fprintf(out, "%s//\n", indent)
			continue
		}
		fmt.Fprintf(out, "%s// %s\n", indent, line)
	}
}

func quote(value string) string {
	return fmt.Sprintf("%q", value)
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}
